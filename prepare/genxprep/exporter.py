"""Exporter – writes H5AD files and supplementary data to the output directory.

Creates the directory structure expected by GenXBrowser::

    <output_dir>/
    ├── <CODE>/
    │   └── <CODE>_full.h5ad
    ├── Metadata/
    │   ├── fas/
    │   │   ├── <CODE>.protein.fas
    │   │   └── <CODE>.RNA.fas
    │   └── Resolved_Gene_Trees.txt
    └── genxbrowser_config.yaml
"""

from __future__ import annotations

import shutil
from pathlib import Path

import anndata as ad

from genxprep.config import ProjectConfig, SpeciesConfig
from genxprep.reporter import Reporter


def export_species(
    adata: ad.AnnData,
    sp: SpeciesConfig,
    output_dir: Path,
    reporter: Reporter,
) -> Path:
    """Write the H5AD file for one species. Returns the output path."""
    vr = reporter.new(f"Export → {sp.code}")

    species_dir = output_dir / sp.code
    species_dir.mkdir(parents=True, exist_ok=True)

    h5ad_path = species_dir / f"{sp.code}_full.h5ad"

    try:
        adata.write_h5ad(h5ad_path)
        vr.success(f"Written: {h5ad_path}")
    except Exception as exc:
        vr.error(f"Failed to write H5AD: {exc}")

    return h5ad_path


def export_sequences(
    sp: SpeciesConfig,
    output_dir: Path,
    reporter: Reporter,
) -> None:
    """Copy FASTA files to the output directory."""
    fas_dir = output_dir / "Metadata" / "fas"
    fas_dir.mkdir(parents=True, exist_ok=True)

    for kind, src_path in [("protein", sp.sequences.protein), ("rna", sp.sequences.rna)]:
        if src_path is None or not src_path.exists():
            continue
        suffix = "protein" if kind == "protein" else "RNA"
        dst = fas_dir / f"{sp.code}.{suffix}.fas"
        try:
            shutil.copy2(src_path, dst)
            reporter.new(f"FASTA → {sp.code}").success(f"Copied {kind} FASTA → {dst}")
        except Exception as exc:
            reporter.new(f"FASTA → {sp.code}").error(f"Failed to copy {kind} FASTA: {exc}")


def export_gene_trees(
    trees: dict[str, str],
    output_dir: Path,
    reporter: Reporter,
) -> None:
    """Write the gene trees file."""
    if not trees:
        return

    dst = output_dir / "Metadata" / "Resolved_Gene_Trees.txt"
    dst.parent.mkdir(parents=True, exist_ok=True)

    try:
        with open(dst, "w") as fh:
            for og_id, newick in sorted(trees.items()):
                fh.write(f"{og_id}:{newick}\n")
        reporter.new("Gene trees export").success(f"Written {len(trees)} trees → {dst}")
    except Exception as exc:
        reporter.new("Gene trees export").error(f"Failed to write gene trees: {exc}")


def copy_gene_trees_file(
    src: Path,
    output_dir: Path,
    reporter: Reporter,
) -> None:
    """Copy gene trees file directly to the output directory."""
    dst = output_dir / "Metadata" / "Resolved_Gene_Trees.txt"
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        shutil.copy2(src, dst)
        reporter.new("Gene trees export").success(f"Copied gene trees → {dst}")
    except Exception as exc:
        reporter.new("Gene trees export").error(f"Failed to copy gene trees: {exc}")


def write_frontend_config(
    config: ProjectConfig,
    output_dir: Path,
    reporter: Reporter,
) -> None:
    """Generate a default genxbrowser_config.yaml for the frontend."""
    cfg_path = output_dir / "genxbrowser_config.yaml"

    content = f"""\
# GenXBrowser frontend configuration
# Generated by genxprep for project: {config.name}

corporate_identity:
  company_name: "{config.name}"
  logo: ""
  about: about.md
  llm_name: ""
  cc_by: ""

access:
  data: True
  download: True

visualization:
  id_column: gene_id
  hide_columns:
    - rna_seq
    - newick_str
"""
    try:
        cfg_path.write_text(content)
        reporter.new("Frontend config").success(f"Written: {cfg_path}")
    except Exception as exc:
        reporter.new("Frontend config").error(f"Failed to write frontend config: {exc}")
